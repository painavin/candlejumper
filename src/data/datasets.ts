import type { BarInterval } from '@shared/contracts/index.js'
import { isBarInterval } from '@shared/contracts/index.js'

/**
 * The bundled OHLCV datasets, served as static files.
 *
 * They live in `public/datasets/` and are fetched at runtime, **not** imported. That's
 * the whole design, and it replaced `import.meta.glob`, which turned every dataset into a
 * JS module.
 *
 * ## Why not bundle them
 *
 * Lazy `import.meta.glob` did split them into one chunk each, so nothing was in the main
 * bundle — but the catalogue defeated that entirely. `listTickers` computed each series'
 * bar count and date span by *loading the series*, which at three datasets was invisible
 * and at six hundred meant 64 MB downloaded before the title screen appeared, three and a
 * half million bar objects retained for the session, and a 4 GB Node heap exhausted under
 * test.
 *
 * A manifest fixes that: `scripts/datasets.mjs` precomputes the counts and spans, so the
 * catalogue is one 60 kB request and a dataset is fetched only when it is played. Serving
 * the files instead of importing them is what makes the manifest possible — a `public/`
 * file has a stable URL, where a bundled chunk has a hashed name only the bundler knows.
 *
 * It is also byte-neutral. Rolldown emitted each dataset as `JSON.parse("…")` inside a JS
 * module, so a minified `.json` file is the same payload without the wrapper.
 *
 * ## Stored gzipped, inflated here
 *
 * For the **deploy**, not the download: the host already compresses text responses in
 * flight, so a plain 472 kB dataset was arriving as ~123 kB either way. What changes is
 * bytes on disk, which is what a static-site size cap measures — 242 MB becomes 63 MB.
 * `scripts/datasets.mjs` does the compressing; `jsonFromBytes` does the inflating, by
 * sniffing the gzip magic number rather than trusting a file extension.
 *
 * ## The cost, and what pays it
 *
 * `public/` file names are not content-hashed, so they cannot be cached immutably by name
 * alone — and a refreshed dataset reuses its name with different contents. That is a real
 * hazard rather than a theoretical one: the run fingerprint keys on bar count and last bar
 * time taken from the *manifest*, so a client holding a stale dataset behind a fresh
 * manifest would file runs under a bucket describing a series it isn't playing. So every
 * dataset request carries `?v=<lastBarTime>` from the manifest, which changes whenever the
 * contents do. That makes the URL safe to cache for a year; see `staticwebapp.config.json`.
 */

/** Where the datasets sit, relative to the site root. */
export const DATASETS_DIR = 'datasets'

/** The catalogue, generated by `scripts/datasets.mjs`. */
export const MANIFEST_FILE = 'manifest.json'

/**
 * Interval tokens as the export tool spells them in a file name.
 *
 * A translation table rather than inference from the timestamps, even though
 * `inferInterval` exists and would work: the file name is a *declaration*, and preferring
 * a guess over it would mean a mislabelled file silently plays as something else. An
 * unrecognised token is treated as unknown rather than assumed daily — see `datasetOf`.
 *
 * Keyed by the tool's vocabulary, valued in the ids the rest of the app uses. Only `Daily`
 * and `Mins30` appear today; the rest are here because the next export will not warn
 * anyone first.
 */
const FILE_INTERVALS: Readonly<Record<string, BarInterval>> = {
  Mins1: '1m',
  Mins2: '2m',
  Mins5: '5m',
  Mins15: '15m',
  Mins30: '30m',
  Hourly: '1h',
  Daily: '1d',
  Weekly: '1wk',
  Monthly: '1mo',
  Quarterly: '3mo',
}

/** One line of the manifest: what the generator can know without interpreting anything. */
export interface DatasetManifestEntry {
  /** File name within `DATASETS_DIR`, e.g. `AAPL.Daily.json`. */
  file: string
  barCount: number
  /** Epoch seconds. */
  firstBarTime: number
  lastBarTime: number
}

/** A manifest entry with its file name read: which ticker, at which interval. */
export interface BundledDataset extends DatasetManifestEntry {
  ticker: string
  interval: BarInterval
}

/**
 * `AAPL.Daily.json` → `{ ticker: 'AAPL', interval: '1d' }`, or `undefined`.
 *
 * A trailing `.gz` is stripped first, so a compressed and an uncompressed dataset read the
 * same. Undefined for a name this build can't read, which the caller drops. Assuming daily
 * would be worse than skipping it: the interval sets the split tolerance, so a monthly file
 * read as daily is rejected for moves that are entirely normal at a month — and a series
 * that quietly plays at the wrong cadence is harder to notice than one that isn't offered.
 */
export function datasetOf(entry: DatasetManifestEntry): BundledDataset | undefined {
  const parts = entry.file.replace(/\.json(\.gz)?$/, '').split('.')
  if (parts.length !== 2) return undefined
  const [ticker, token] = parts
  const interval = token === undefined ? undefined : FILE_INTERVALS[token]
  if (!ticker || !interval || !isBarInterval(interval)) return undefined
  return { ...entry, ticker, interval }
}

/** Fetches and parses one JSON file under the site root. Injected, so tests read from disk. */
export type JsonFetcher = (path: string) => Promise<unknown>

/**
 * Gzip's magic number.
 *
 * Datasets are stored compressed for the deploy's sake — 242 MB of JSON is 63 MB gzipped,
 * and a static-site size cap measures bytes on disk. They're inflated here rather than by
 * the browser, because `Content-Encoding` on a static file is a promise the CDN has to keep
 * and there is no way to test it before it is deployed.
 */
const GZIP_MAGIC = [0x1f, 0x8b]

/**
 * Reads JSON from bytes, inflating first if they turn out to be gzipped.
 *
 * **Sniffed rather than taken from the file name**, which matters more than it looks. A
 * CDN that recognises `.gz` and helpfully decodes it — setting `Content-Encoding` so the
 * browser inflates before we see the body — would hand us plain JSON, and an unconditional
 * inflate would fail on every dataset with an error pointing nowhere near the cause. Gzip
 * is self-describing, so the bytes can just be asked.
 */
export async function jsonFromBytes(bytes: Uint8Array, label: string): Promise<unknown> {
  const gzipped = bytes[0] === GZIP_MAGIC[0] && bytes[1] === GZIP_MAGIC[1]
  if (!gzipped) return JSON.parse(new TextDecoder().decode(bytes))

  try {
    const stream = new Blob([bytes as BlobPart])
      .stream()
      .pipeThrough(new DecompressionStream('gzip'))
    return await new Response(stream).json()
  } catch (error) {
    throw new Error(`Couldn't decompress ${label}`, { cause: error })
  }
}

/**
 * The real fetcher: relative to the site's base URL, so it works under a sub-path deploy
 * and inside the desktop and mobile shells, which serve the same `dist` from their own
 * origin.
 */
export function createHttpJsonFetcher(base = import.meta.env.BASE_URL): JsonFetcher {
  return async (path) => {
    const response = await fetch(`${base}${path}`)
    if (!response.ok) {
      throw new Error(`Couldn't load ${path}: ${response.status} ${response.statusText}`)
    }
    return jsonFromBytes(new Uint8Array(await response.arrayBuffer()), path)
  }
}

/**
 * Reads the manifest, dropping anything malformed.
 *
 * Untrusted despite being our own build output, because it arrives over the network and
 * can be stale, truncated, or served from a cache older than the app. A bad *line* costs
 * one dataset; only a manifest that isn't a list at all is fatal, because then there is no
 * catalogue to show and pretending otherwise would present an empty game as a working one.
 */
export function parseManifest(raw: unknown, label: string): BundledDataset[] {
  if (!Array.isArray(raw)) throw new Error(`${label}: expected an array of datasets`)

  const datasets: BundledDataset[] = []
  for (const line of raw) {
    if (typeof line !== 'object' || line === null) continue
    const { file, barCount, firstBarTime, lastBarTime } = line as Record<string, unknown>
    if (typeof file !== 'string' || file.length === 0) continue
    if (!Number.isInteger(barCount) || (barCount as number) <= 0) continue
    if (!Number.isFinite(firstBarTime) || !Number.isFinite(lastBarTime)) continue

    const dataset = datasetOf({
      file,
      barCount: barCount as number,
      firstBarTime: firstBarTime as number,
      lastBarTime: lastBarTime as number,
    })
    if (dataset) datasets.push(dataset)
  }
  return datasets
}

/** Path of the manifest, for a `JsonFetcher`. */
export function manifestPath(): string {
  return `${DATASETS_DIR}/${MANIFEST_FILE}`
}

/**
 * Path of one dataset, carrying its last bar time as a cache key.
 *
 * The query string is what lets the file be cached for a year under a name that isn't
 * content-hashed — see the note at the top of this file.
 */
export function datasetPath(dataset: BundledDataset): string {
  return `${DATASETS_DIR}/${dataset.file}?v=${dataset.lastBarTime}`
}
